"""K10: the single-use and binding guards of the dispatcher and of the launcher generated for this operation, each
exercised directly. The family's conformance suite (the frozen core's tests/conformance.py) leaves these unpinned for
K10: a reviewer's mutants on the generated bytes survived it (review of 2026-10-02: D01, D02, D03, D04, D06, D07, D08,
D10, D12, D13, D16, L01). The worst case was single use itself: the core's test of it passes when the spawn marker is
not written, because its transport raises an AssertionError that the dispatcher's own "except Exception" swallows, and
the FileExistsError it expects then comes from the receipt file of the first resume, AFTER the transport was reached.
Here the transport counts its calls. Synthetic local files only: no SSH, no host, no key, no GO."""
import hashlib
import json
import os
from datetime import datetime,timedelta
from pathlib import Path
import subprocess
import sys

import pytest

import family as f
import k10

def sha(raw):return hashlib.sha256(raw).hexdigest()

def counting(dispatch,calls):
    inner=dispatch.fake()
    def run(payload,**kwargs):
        calls.append(sha(payload));return inner(payload,**kwargs)
    return run

def test_second_resume_never_reaches_the_transport(tmp_path):
    docs,_=k10.case();dispatch=f.Dispatch(docs,tmp_path);published=dispatch.proof(dispatch.prepare());calls=[]
    assert dispatch.resume(published,counting(dispatch,calls))['status']=='KNOWN_PARTIAL' and calls==[sha(dispatch.payload)]
    with pytest.raises(FileExistsError):dispatch.resume(published,counting(dispatch,calls))
    assert len(calls)==1,'the payload was offered to the transport twice'
    # even when the receipts of the first resume are gone (a wiped attempt directory keeps spawn.claim only)
    attempt=Path(dispatch.config['attempt_directory'])
    for name in ('stdout.private.json','stderr.private','exit.json'):(attempt/name).unlink()
    with pytest.raises(FileExistsError):dispatch.resume(published,counting(dispatch,calls))
    assert len(calls)==1

def test_what_is_sent_is_the_bundle_of_the_authenticated_documents(tmp_path):
    docs,_=k10.case();k=docs.k;dispatch=f.Dispatch(docs,tmp_path)
    other=dispatch.payload.replace(b"exit_code=3;result=module.run(",b"exit_code=3;result=module.run (")
    assert other!=dispatch.payload
    dispatch.config['payload']=dispatch.put('payload',other);dispatch.pin=dispatch.put('config',f.canonical(dispatch.config))
    assert f.refusal(dispatch.prepare)=='FINAL_BUNDLE_BYTES' and not dispatch.claims()
    # a bundle of ANOTHER request of the same operation (the spare) under the primary's config
    docs2,_=k10.case(now=docs.now+timedelta(minutes=1));d2=f.Dispatch(docs2,tmp_path/'x') if (tmp_path/'x').mkdir() is None else None
    dispatch.config['payload']=dispatch.put('payload',d2.payload);dispatch.pin=dispatch.put('config',f.canonical(dispatch.config))
    assert f.refusal(dispatch.prepare)=='FINAL_BUNDLE_BYTES' and not dispatch.claims()

def test_config_window_wider_than_a_signed_window_is_refused_before_the_claim(tmp_path):
    docs,_=k10.case();dispatch=f.Dispatch(docs,tmp_path);now=docs.now
    for field,value in (('not_before',(now-timedelta(seconds=1)).isoformat()),('not_after',(now+timedelta(minutes=5,seconds=1)).isoformat())):
        saved=dispatch.config[field];dispatch.config[field]=value
        dispatch.config['latest_start']=(datetime.fromisoformat(dispatch.config['not_after'])-timedelta(seconds=80)).isoformat()
        dispatch.save(rebind=False);assert f.refusal(lambda:dispatch.prepare(clock=lambda:now))=='INNER_WINDOW' and not dispatch.claims()
        dispatch.config[field]=saved
    # the GO narrower than the config
    dispatch.config['latest_start']=(now+timedelta(seconds=220)).isoformat()
    docs.go['not_after']=(now+timedelta(minutes=4)).isoformat();dispatch.save()
    assert f.refusal(dispatch.prepare)=='INNER_WINDOW' and not dispatch.claims()

def test_budget_pair_and_inner_hash_chain_and_command_pin_before_the_claim(tmp_path):
    docs,_=k10.case();k=docs.k
    d=tmp_path/'a';d.mkdir();dispatch=f.Dispatch(docs,d)
    dispatch.config['watchdog_seconds']=79;dispatch.config['latest_start']=(docs.now+timedelta(seconds=221)).isoformat();dispatch.save(rebind=False)
    assert f.refusal(dispatch.prepare)=='PREFLIGHT_BUDGET' and not dispatch.claims()
    d=tmp_path/'b';d.mkdir();dispatch=f.Dispatch(docs,d)
    dispatch.config['command_sha256']='a'*64;dispatch.save(rebind=False)
    assert f.refusal(dispatch.prepare) in ('GO_TRANSPORT_BINDING',) and not dispatch.claims()
    dispatch.save()                                        # the GO now names the wrong pin too: only COMMAND_PIN is left to refuse
    assert f.refusal(dispatch.prepare)=='COMMAND_PIN' and not dispatch.claims()
    # a broken chain between the documents: the dispatcher's own check, before the source's
    d=tmp_path/'c';d.mkdir();docs2,_=k10.case();dispatch=f.Dispatch(docs2,d)
    docs2.go['authority_sha256']='b'*64;raw=docs2.raw()
    for key,blob in (('go',raw[2]),):dispatch.config[key]=dispatch.put(key,blob)
    payload=k.l.build(k.source,*raw,expected_payload_sha256=sha(k.source),expected_request_sha256=sha(raw[0]),expected_authority_sha256=sha(raw[1]),expected_go_sha256=sha(raw[2]))
