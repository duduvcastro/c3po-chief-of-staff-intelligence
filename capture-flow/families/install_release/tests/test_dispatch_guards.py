def test_resume_needs_the_claim_of_prepare_and_the_exact_intent(tmp_path):
    docs,_=k10.case();dispatch=f.Dispatch(docs,tmp_path);prepared=dispatch.prepare();published=dispatch.proof(prepared);calls=[]
    claim=dispatch.claims()[0];raw=claim.read_bytes();claim.unlink();claim.write_bytes(raw.replace(b'GO_CLAIM_V1',b'GO_CLAIM_V2'));os.chmod(claim,0o600)
    with pytest.raises(ValueError):dispatch.resume(published,counting(dispatch,calls))
    assert calls==[] and not (Path(dispatch.config['attempt_directory'])/'spawn.claim').exists()
    claim.unlink();claim.write_bytes(raw);os.chmod(claim,0o600)
    # an intent with another payload hash, published with its own hash
    intent_path=Path(dispatch.config['attempt_directory'])/'intent.json';intent=json.loads(intent_path.read_bytes())
    forged=f.canonical(dict(intent,payload_sha256='c'*64));intent_path.unlink();intent_path.write_bytes(forged);os.chmod(intent_path,0o600)
    proof=dispatch.proof({'intent_sha256':sha(forged)})
    with pytest.raises(ValueError):dispatch.resume(proof,counting(dispatch,calls))
    assert calls==[] and not (Path(dispatch.config['attempt_directory'])/'spawn.claim').exists()

def test_receipt_must_name_the_payload_it_ran_and_partial_receipts_are_bound_too(tmp_path):
    for index,status in enumerate(('KNOWN_COMPLETE','KNOWN_PARTIAL')):
        d=tmp_path/str(index);d.mkdir();docs,_=k10.case();dispatch=f.Dispatch(docs,d);m=docs.k.m
        out=f.canonical({'schema':m.RECEIPT_SCHEMA,'request_sha256':dispatch.config['request']['sha256'],'go_sha256':dispatch.config['go']['sha256'],'payload_sha256':'d'*64})
        result=dispatch.resume(dispatch.proof(dispatch.prepare()),dispatch.fake(out=out,status=status))
        assert result['status']=='UNCERTAIN' and result['code']=='TRANSPORT_OR_RECEIPT_REFUSED'

def test_launcher_refuses_a_source_that_is_not_the_pinned_one_on_stdin():
    docs,_=k10.case();k=docs.k;raws=docs.raw()
    payload=k.l.build(k.source,*raws,expected_payload_sha256=sha(k.source),expected_request_sha256=sha(raws[0]),expected_authority_sha256=sha(raws[1]),expected_go_sha256=sha(raws[2]))
    text=payload.decode();pin=sha(k.source);assert text.count("'payload': '%s'"%pin)==1
    forged=text.replace("'payload': '%s'"%pin,"'payload': '%s'"%('e'*64)).encode()
    done=subprocess.run([sys.executable,'-I','-B','-'],input=forged,stdout=subprocess.PIPE,stderr=subprocess.PIPE,env={'PATH':'/usr/bin:/bin'},timeout=60)
    out=json.loads(done.stdout);assert done.returncode==1 and done.stderr==b'' and out=={'schema':'HOSTOPS_STDIN_RESULT_V1','status':'REFUSED','code':'STDIN_SOURCE_PIN'}
    with pytest.raises(ValueError):k.l.build(k.source+b'\n',*raws,expected_payload_sha256=sha(k.source),expected_request_sha256=sha(raws[0]),expected_authority_sha256=sha(raws[1]),expected_go_sha256=sha(raws[2]))

def test_config_window_wider_than_the_request_alone_is_refused_before_the_claim(tmp_path):
    """Authority and GO signed for a longer window than the request: the config may not use the longer one."""
    docs,_=k10.case();now=docs.now;wide=(now+timedelta(minutes=10)).isoformat()
    docs.authority['not_after']=wide;docs.go['not_after']=wide;docs.chain();docs.authenticate()
    dispatch=f.Dispatch(docs,tmp_path)
    dispatch.config['not_after']=wide;dispatch.config['latest_start']=(now+timedelta(minutes=10)-timedelta(seconds=80)).isoformat();dispatch.save()
    assert f.refusal(dispatch.prepare)=='INNER_WINDOW' and not dispatch.claims()
