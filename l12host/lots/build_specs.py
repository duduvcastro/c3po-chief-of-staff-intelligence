def down_matches_up(up_real_dir, layout_path, extra, m):
    """v3.3 (lots review F1, MEDIUM): the REAL DOWN uses byte-identical K9 request, GO, runner and capture_launch plan
    bytes as the UP REAL spec, and the same grid id. The comparisons come first (each mismatch has its own code), then
    the whole UP dir is re-validated (check_real). Writes nothing."""
    try:
        up_dir, _, listed = real_dir(up_real_dir)
    except rt.Hold as error:
        raise Refused("REAL_DOWN_UP_DIR_INVALID", rt.safe_code(error)) from None
    refuse("UP.SPEC.json" in listed and all(rel in listed for rel in (K9_REQUEST, K9_GO, RUNNER_REL, UP_CAPTURE_ANCHOR)),
           "REAL_DOWN_UP_DIR_NOT_AN_UP_REAL_DIR")
    up = {rel: read_file(up_dir / rel) for rel in (K9_REQUEST, K9_GO, RUNNER_REL, UP_CAPTURE_ANCHOR)}
    up_grid = rt.strict(up[K9_REQUEST], kind=Refused).get("grid")
    up_grid_id = up_grid.get("id") if type(up_grid) is dict else None
    refuse(up_grid_id == m["grid"]["id"], "REAL_DOWN_GRID_NOT_THE_UP_ONE", [up_grid_id, m["grid"]["id"]])
    refuse(up[K9_REQUEST] == extra[K9_REQUEST], "REAL_DOWN_K9_REQUEST_NOT_THE_UP_ONE")
    refuse(up[K9_GO] == extra[K9_GO], "REAL_DOWN_K9_GO_NOT_THE_UP_ONE")
    refuse(up[RUNNER_REL] == extra[RUNNER_REL], "REAL_DOWN_RUNNER_NOT_THE_UP_ONE")
    refuse(up[UP_CAPTURE_ANCHOR] == extra[DOWN_CAPTURE_PLAN], "REAL_DOWN_CAPTURE_PLAN_NOT_THE_UP_ONE")
    try:
        checked = check_real(str(up_dir), layout_path)
    except rt.Hold as error:
        raise Refused("REAL_DOWN_UP_DIR_INVALID", rt.safe_code(error)) from None
    refuse(checked["lot"] == "UP", "REAL_DOWN_UP_DIR_NOT_AN_UP_REAL_DIR")
    return {"up_real_dir": str(up_dir), "up_spec_sha256": checked["spec_sha256"],
            "up_sha256sums_sha256": checked["sha256sums_sha256"], "grid": up_grid_id,
            "k9_request_sha256": rt.sha(up[K9_REQUEST]), "go_sha256": rt.sha(up[K9_GO]),
            "runner_sha256": rt.sha(up[RUNNER_REL]), "capture_launch_plan_sha256": rt.sha(up[UP_CAPTURE_ANCHOR]),
            "byte_identical": True}


