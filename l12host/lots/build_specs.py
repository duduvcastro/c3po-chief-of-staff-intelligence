def fill(spec, tmp):
    """Replace ONLY the declared @P_...@ placeholders with synthetic values (files -> synthetic bytes in tmp)."""
    spec = copy.deepcopy(spec)
    module = Path(tmp) / "synthetic_module.py"
    module.write_bytes(SYNTHETIC_MODULE)
    doc = Path(tmp) / "synthetic_doc.json"
    doc.write_bytes(b'{"synthetic":true}')
    for rel, local in list(spec["files"].items()):
        if local.startswith("@P_"):
            spec["files"][rel] = str(module if rel.endswith(".py") else doc)
    values = {"@P_MANIFEST_DIRECTORY@": "/var/lib/c3po-capacity-e04/payload",
              "@P_E6_DOCUMENT_PATH@": "/var/lib/c3po/r2d2-v2-k9-20261012/e6/E6_04.json",
              "@P_J4_GENERAL_SOURCE_IDENTITY@": "SYNTHETIC_FILL_IN"}

    def walk(value):
        if isinstance(value, str) and value.startswith("@P_") and value.endswith("@"):
            return values.get(value, hashlib.sha256(value.encode("ascii")).hexdigest())
        if isinstance(value, dict):
            return {k: walk(v) for k, v in value.items()}
        if isinstance(value, list):
            return [walk(v) for v in value]
        return value
    return walk(spec)


