def write_file(target, rel, raw):
    path = target / rel
    if path.parent != target and not path.parent.exists():
        os.mkdir(str(path.parent), 0o700)
    fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        view = memoryview(raw)
        while view:
            view = view[os.write(fd, view):]
        os.fsync(fd)
    finally:
        os.close(fd)
    return rt.sha(raw)


