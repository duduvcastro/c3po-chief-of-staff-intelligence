def same_inode(a, b):
    return (a.st_dev, a.st_ino) == (b.st_dev, b.st_ino)


def sealed_roots():
    """The family root and, when it is part of a sealed delivery (a top SHA256SUMS that lists l12host/SHA256SUMS), the
    delivery root: no REAL spec may be written under either."""
    roots = [FAMILY]
    top = FAMILY.parent / "SHA256SUMS"
    try:
        if any(line.endswith("  " + FAMILY.name + "/SHA256SUMS") for line in top.read_text("ascii").splitlines()):
            roots.append(FAMILY.parent)
    except (OSError, UnicodeDecodeError):
        pass
    return [(root, os.stat(str(root))) for root in roots]


def guard_out_dir(out_dir):
    """The REAL output directory: neither it nor any existing ancestor (symlinks resolved; compared by device and
    inode, so letter case and links cannot alias) is the family root or its sealed delivery; and it does not exist."""
    target = Path(os.path.abspath(str(out_dir)))
    probe = target
    while not os.path.lexists(str(probe)):
        probe = probe.parent
    real = Path(os.path.realpath(str(probe)))
    roots = sealed_roots()
    for ancestor in [real] + list(real.parents):
        here = os.stat(str(ancestor))
        for root, info in roots:
            refuse(not same_inode(here, info), "REAL_SPEC_OUT_DIR_INSIDE_FAMILY", root.name)
    refuse(probe != target, "REAL_SPEC_OUT_DIR_EXISTS")
    return target


def recheck_created(target):
    real = Path(os.path.realpath(str(target)))
    roots = sealed_roots()
    for ancestor in [real] + list(real.parents):
        here = os.stat(str(ancestor))
        refuse(all(not same_inode(here, info) for _, info in roots), "REAL_SPEC_OUT_DIR_INSIDE_FAMILY")


