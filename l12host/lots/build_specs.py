def unsealed_sha256(raw):
    """sha256 of the verifier with its ONE `APPROVED_REGISTRY_PINS = ...` line reset to the delivered `{}` (Codex's seal
    changes only that line): equal to CODEX_R2_UNSEALED_SHA256 iff the bodies are R2's. Informational, never a gate."""
    lines = raw.split(b"\n")
    hits = [i for i, line in enumerate(lines) if line.startswith(b"APPROVED_REGISTRY_PINS = ")]
    if len(hits) != 1:
        return None
    lines[hits[0]] = b"APPROVED_REGISTRY_PINS = {}"
    return rt.sha(b"\n".join(lines))


def canonical_doc(raw, code):
    try:
        return rt.strict(raw, kind=Refused)
    except rt.Hold:
        raise Refused(code) from None


def k9_real_bindings(lot, m, manifest_raw, constants, raw, secrets_root, networks, lay):
    """The REAL K9 files of one lot (`raw`: verifier, policy, review, publication bytes and {name: original bytes})
    against the plans run `m` (manifest bytes `manifest_raw`, plan `constants`): returns {signed rel: bytes} of the 11
    REAL files and the KILL record bytes. Every check here precedes any write; the runtime repeats the bindings it can
    see at bind and before every effect (validate_k9_real)."""
    source = rt.k9_real_source(raw["verifier"], Refused)
    pins = source["ORIGINAL_PINS"]
    refuse({"act_b", "release", "policy"} <= set(pins) and pins["release"] == RELEASE and pins["policy"] == POLICY
           and pins["act_b"] == constants.get("act_b_sha256"), "REAL_K9_ORIGINAL_PINS_NOT_THE_PLANS_ONES")
    refuse(set(raw["originals"]) == set(pins), "REAL_K9_ORIGINALS_NOT_THE_VERIFIER_ONES",
           sorted(set(pins) ^ set(raw["originals"]))[:1] or None)
    for name in sorted(pins):
        refuse(rt.sha(raw["originals"][name]) == pins[name], "REAL_K9_ORIGINAL_NOT_THE_PINNED_ONE", name)
    policy = canonical_doc(raw["policy"], "REAL_K9_POLICY_INVALID")
    refuse(set(policy) == rt.K9_REAL_POLICY_KEYS and policy["schema"] == rt.K9_REAL_POLICY_SCHEMA
           and policy["mode"] == "REAL" and policy["lot"] == lot and policy["epoch"] == "R2D2-V2-SHADOW-2026-10-12"
           and policy["day"] == "2026-10-12", "REAL_K9_POLICY_INVALID")
    refuse(source["APPROVED_REGISTRY_PINS"].get(lot) == rt.sha(raw["policy"]), "REAL_K9_POLICY_NOT_SEALED_IN_THE_VERIFIER")
    refuse(policy["grid"] == m["grid"]["id"] and policy["request_sha256"] == m["request_sha256"]
           and policy["go_sha256"] == m["go_sha256"], "REAL_K9_POLICY_NOT_THIS_GO_REQUEST_GRID")
    canonical_doc(raw["review"], "REAL_K9_REVIEW_INVALID")
    refuse(rt.sha(raw["review"]) == policy["review_decision_sha256"], "REAL_K9_REVIEW_NOT_THE_REGISTERED_ONE")
    pub = canonical_doc(raw["publication"], "REAL_K9_PUBLICATION_INVALID")
    refuse(rt.sha(raw["publication"]) == policy["publication_sha256"], "REAL_K9_PUBLICATION_NOT_THE_REGISTERED_ONE")
    refuse(set(pub) == PUBLICATION_KEYS and pub["schema"] == "K9_GO_04_PUBLICATION_V1"
           and pub["original_sha256"] == m["go_sha256"] and pub["created_at"] == pub["updated_at"] == pub["published_at"]
           and rt.pin(pub["body_sha256"]) and all(pub[k] == pub["body_sha256"] for k in PUBLICATION_BODIES),
           "REAL_K9_PUBLICATION_NOT_THE_GO_ONE")
    reg = policy["originals"]
    refuse(type(reg) is dict and set(reg) == set(pins) and all(
        type(r) is dict and set(r) == {"file", "sha256"} and r["sha256"] == pins[n] for n, r in reg.items()),
        "REAL_K9_POLICY_ORIGINALS_NOT_THE_VERIFIER_ONES")
    paths = [r["file"] for r in reg.values()]
    refuse(all(type(p) is str and rt.K9_REAL_ORIGINAL_REL.fullmatch(p) and p not in rt.K9_REAL_FIXED_FILES
               for p in paths) and len(set(paths)) == len(paths), "REAL_K9_ORIGINAL_PATH_INVALID")
    rows = k9_rows(m, secrets_root, networks)
    ops = policy["operations"]
    refuse(type(ops) is dict and set(ops) == set(m["steps"]), "REAL_K9_POLICY_OPERATIONS_NOT_THE_TWELVE")
    for op, step in m["steps"].items():
        refuse(type(ops[op]) is dict and ops[op].get("plan_sha256") == step["plan_sha256"],
               "REAL_K9_POLICY_PLAN_NOT_THE_MANIFEST_ONE", op)
        refuse(ops[op].get("effect_sha256") == rt.sha(rt.canonical(rows[op]["row"])),
               "REAL_K9_POLICY_EFFECT_NOT_THE_DERIVED_ROW", op)
    sources = {rt.K9_REAL_VERIFIER: ("verifier",), rt.K9_REAL_POLICY: ("policy",), rt.K9_REAL_REVIEW: ("review",),
               rt.K9_REAL_PUBLICATION: ("publication",)}
    sources.update({reg[name]["file"]: ("originals", name) for name in sorted(pins)})
    files = {rel: raw[key[0]] if len(key) == 1 else raw["originals"][key[1]] for rel, key in sources.items()}
    return files, sources, kill_record(m, manifest_raw, secrets_root, networks, lay)


