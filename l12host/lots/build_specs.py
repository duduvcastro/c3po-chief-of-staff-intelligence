def substitute(spec, values):
    """Every @P_...@ of the lot from `values` (a placeholder that names a file -> that file's absolute path, its bytes
    copied at write); no other key, none left."""
    wanted = placeholders(spec)
    refuse(type(values) is dict and all(type(k) is str and type(v) is str and v and not v.startswith("@P_")
                                        for k, v in values.items()), "REAL_VALUES_INVALID")
    refuse(not set(values) - wanted, "REAL_VALUES_UNKNOWN_PLACEHOLDER", sorted(set(values) - wanted)[:1] or None)
    refuse(not wanted - set(values), "REAL_SPEC_PLACEHOLDER_UNFILLED", sorted(wanted - set(values))[:1] or None)
    file_placeholders = {v for v in spec["files"].values() if v in wanted}
    for name in file_placeholders:
        read_file(values[name])

    def walk(value):
        if isinstance(value, str) and value in wanted:
            return values[value]
        if isinstance(value, dict):
            return {k: walk(v) for k, v in value.items()}
        if isinstance(value, list):
            return [walk(v) for v in value]
        return value
    out = walk(spec)
    refuse(not placeholders(out), "REAL_SPEC_PLACEHOLDER_UNFILLED")
    return out


