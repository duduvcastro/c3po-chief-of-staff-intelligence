def real_dir(out_dir):
    """A written REAL dir, integrity only: (absolute target, SHA256SUMS bytes, {rel: sha256}); SHA256SUMS lists every
    file exactly and every listed byte matches. v3.3 (lots review LOW 6): a relative DIR is made absolute, as `write`
    does, and a DIR that is not a real directory is refused as such."""
    target = Path(os.path.abspath(str(out_dir)))
    refuse(target.is_dir() and not target.is_symlink(), "REAL_SPEC_DIR_NOT_A_DIRECTORY")
    sums = read_file(target / "SHA256SUMS")
    listed = {}
    for line in sums.decode("ascii").splitlines():
        digest, _, rel = line.partition("  ")
        refuse(len(digest) == 64 and rel and rel not in listed, "REAL_DIR_SUMS_INVALID")
        listed[rel] = digest
    present = {p.relative_to(target).as_posix() for p in target.rglob("*") if not p.is_dir()} - {"SHA256SUMS"}
    refuse(set(listed) == present, "REAL_DIR_FILE_SET_MISMATCH")
    refuse(all(rt.sha(read_file(target / rel)) == digest for rel, digest in listed.items()), "REAL_DIR_BYTES_MISMATCH")
    return target, sums, listed


def check_real(out_dir, layout_path):
    """Re-checks a written REAL dir; writes nothing."""
    target, sums, listed = real_dir(out_dir)
    names = [n for n in listed if n.endswith(".SPEC.json")]
    refuse(len(names) == 1 and names[0] in ("UP.SPEC.json", "DOWN.SPEC.json"), "REAL_DIR_SPEC_INVALID")
    spec = bind.loose_json(target / names[0])
    refuse(spec.get("lot") + ".SPEC.json" == names[0] and not placeholders(spec), "REAL_DIR_SPEC_INVALID")
    request_raw = read_file(target / K9_REQUEST)
    request = rt.strict(request_raw, kind=Refused)
    grid = request.get("grid")
    refuse(type(grid) is dict and grid.get("id") in ELECTED_GRIDS and grid == generator().grid_block(grid["id"]),
           "REAL_PLANS_GRID_NOT_ELECTED")
    if spec["lot"] == "UP":
        # v3.3 (F1): the UP dir carries the capture_launch plan of ITS plans run, bound to its request and GO
        refuse(UP_CAPTURE_ANCHOR in listed, "REAL_UP_CAPTURE_ANCHOR_INVALID")
        anchor = rt.strict(read_file(target / UP_CAPTURE_ANCHOR), kind=Refused)
        refuse(anchor.get("k9_operation") == "capture_launch" and anchor.get("request_sha256") == rt.sha(request_raw)
               and anchor.get("go_sha256") == rt.sha(read_file(target / K9_GO))
               and type(anchor.get("step_row")) is dict and anchor["step_row"].get("grid") == grid,
               "REAL_UP_CAPTURE_ANCHOR_INVALID")
    windows = windows_or_refuse(spec)
    lay = rt.validate_layout(bind.loose_json(layout_path), Refused)
    real = check_real_k9(target, listed, spec, request_raw, lay)
    bind.build_lot(spec, lay, runtime_stub(lay), validation_instant(spec["owner_deadline"]), target, physical=True)
    return {"status": "REAL_SPEC_DIR_VALID", "lot": spec["lot"], "spec_sha256": listed[names[0]],
            "sha256sums_sha256": rt.sha(sums), "files": len(listed), "grid": grid["id"],
            "layout_sha256": rt.sha(rt.canonical(lay)), "start_windows": windows, "k9_real": real,
            "kill_record": {"file": KILL_RECORD, "sha256": listed[KILL_RECORD]}}


def check_real_k9(target, listed, spec, request_raw, lay):
    """v3.3f, `validate`: the dir's REAL K9 files and records re-bound exactly as `write` bound them (the KILL record
    re-derived byte for byte from the recorded manifest, this layout and the spec's secrets root / networks)."""
    k9 = spec.get("k9") or {}
    refuse(k9.get("networks") == NETWORKS, "REAL_NETWORKS_NOT_DNET")
    needed = (MANIFEST_RECORD, KILL_RECORD, K9_GO, RUNNER_REL) + rt.K9_REAL_FIXED_FILES
    refuse(all(rel in listed for rel in needed) and all(spec["files"].get(rel) == rel for rel in rt.K9_REAL_FIXED_FILES),
           "REAL_DIR_K9_REAL_FILES_ABSENT")
    manifest_raw = read_file(target / MANIFEST_RECORD)
    m = canonical_doc(manifest_raw, "REAL_DIR_MANIFEST_RECORD_NOT_THIS_RUN")
    refuse(m.get("request_sha256") == rt.sha(request_raw) and m.get("go_sha256") == rt.sha(read_file(target / K9_GO))
           and type(m.get("steps")) is dict and set(k9["plans"]) <= set(m["steps"])
           and all(m["steps"][op]["plan_sha256"] == listed.get(rel) for op, rel in k9["plans"].items())
           and m.get("runner", {}).get("sha256") == listed[RUNNER_REL]
           and m.get("grid") == rt.strict(request_raw, kind=Refused).get("grid"), "REAL_DIR_MANIFEST_RECORD_NOT_THIS_RUN")
