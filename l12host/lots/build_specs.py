def z(text):
    return text.replace("+00:00", "Z")


def at_minus(text, seconds):
    return rt.iso(rt.stamp(z(text)) - __import__("datetime").timedelta(seconds=seconds))


def at_plus(text, seconds):
    return rt.iso(rt.stamp(z(text)) + __import__("datetime").timedelta(seconds=seconds))


