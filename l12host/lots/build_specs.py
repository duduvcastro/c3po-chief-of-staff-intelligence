def slack_table(spec):
    """budget floor vs effect lateness of every K9 row of a spec (CONTRACT 9.3)."""
    rows = []
    for t in spec["tasks"]:
        d = t["effect"].get("docker")
        if d:
            floor = d["timeout_seconds"] + DOCKER_MARGIN
            rows.append({"target": t["operation"], "budget": t["budget_seconds"], "kill": d["timeout_seconds"],
                         "effect_floor": floor, "max_effect_lateness": t["budget_seconds"] - floor,
                         "slack_beyond_allowance": t["budget_seconds"] - floor - rt.GATE_ALLOWANCE_SECONDS})
    for s in (spec["extended"] or {}).get("steps", []):
        d = (s["effect"] or {}).get("docker")
        if d:
            extra = 2 * rt.GATE_ALLOWANCE_SECONDS if s["step"] == "capture_launch" else 0
            floor = d["timeout_seconds"] + DOCKER_MARGIN
            rows.append({"target": s["step"], "budget": s["ceiling_seconds"], "kill": d["timeout_seconds"],
                         "effect_floor": floor, "max_effect_lateness": s["ceiling_seconds"] - floor - extra,
                         "slack_beyond_allowance": s["ceiling_seconds"] - floor - rt.GATE_ALLOWANCE_SECONDS - extra})
    return rows


