def write(path, spec, comment):
    raw = (json.dumps({"_comment": comment, "spec": spec}, sort_keys=True, indent=1) + "\n").encode("ascii")
    fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        os.write(fd, raw)
    finally:
        os.close(fd)
    return rt.sha(raw)


def placeholders(value, out=None):
    out = set() if out is None else out
    if isinstance(value, str) and value.startswith("@P_") and value.endswith("@"):
        out.add(value)
    elif isinstance(value, dict):
        for v in value.values():
            placeholders(v, out)
    elif isinstance(value, list):
        for v in value:
            placeholders(v, out)
    return out


