def slack_table(spec):
    """budget floor vs effect lateness of every K9 row of a spec (CONTRACT 9.3)."""
    rows = []
    for t in spec["tasks"]:
        d = t["effect"].get("docker")
        if d:
            floor = d["timeout_seconds"] + DOCKER_MARGIN
            rows.append({"target": t["operation"], "budget": t["budget_seconds"], "kill": d["timeout_seconds"],
                         "effect_floor": floor, "max_effect_lateness": t["budget_seconds"] - floor,
                         "slack_beyond_allowance": t["budget_seconds"] - floor - rt.GATE_ALLOWANCE_SECONDS})
    for s in (spec["extended"] or {}).get("steps", []):
        d = (s["effect"] or {}).get("docker")
        if d:
            extra = 2 * rt.GATE_ALLOWANCE_SECONDS if s["step"] == "capture_launch" else 0
            floor = d["timeout_seconds"] + DOCKER_MARGIN
            rows.append({"target": s["step"], "budget": s["ceiling_seconds"], "kill": d["timeout_seconds"],
                         "effect_floor": floor, "max_effect_lateness": s["ceiling_seconds"] - floor - extra,
                         "slack_beyond_allowance": s["ceiling_seconds"] - floor - rt.GATE_ALLOWANCE_SECONDS - extra})
    return rows


def start_margin(at, horizon=6 * 3600):
    """Seconds from the instant `at` to the first second the ENGINE's start-minute rule refuses."""
    for k in range(horizon):
        if fx.start_minute_violation(at + timedelta(seconds=k)) is not None:
            return k
    return horizon


def start_windows(spec):
    """Every slot of a spec, by instant: its margin to the engine's next forbidden second and whether the whole
    [at, at + 60 s] + 45 s is allowed (margin > 105 s)."""
    rows = []
    for owner in list(spec["tasks"]) + list((spec["extended"] or {}).get("steps", [])):
        for s in owner["slots"]:
            at = rt.stamp(s["at"], rt.Hold)
            margin = start_margin(at)
            rows.append({"slot": s["slot"], "target": owner.get("operation") or owner.get("step"), "at": s["at"],
                         "brt": at.astimezone(rt.BRT).strftime("%a %d/%m %H:%M:%S"), "margin_seconds": margin,
                         "needed_seconds": START_WINDOW_SECONDS + 1, "ok": margin > START_WINDOW_SECONDS})
    return sorted(rows, key=lambda r: r["at"])


