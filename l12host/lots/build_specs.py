def kill_with_slack(step):
    """v3.1 (finding 8): the inner KILL of an UP row leaves >= 30 s of slack beyond (effect floor + gate allowance):
    KILL = min(generator KILL, budget - 20 - 15 - 30). For a LAUNCH step the generator's KILL is budget - 35 (the
    runner stops itself at run_not_after - 60 = start + budget - 90 and has < 55 s to write its DEADLINE receipt);
    with KILL = budget - 65 that window is 25 s + the effect lateness (Codex ruling requested; CONTRACT 9.3)."""
    return min(step["l12_effect"]["docker"]["timeout_seconds"], step["budget_seconds"] - SLACK_KILL)


def convert(step, secrets_root, networks, *, slack=True):
    """The generator's K9STEP row (v1 shape) -> the v3 CONTAINER row: network per class, env files and the emitter
    mount re-rooted at the secrets root parameter, receipt FILE, no `mode` (ATTACHED is the only mode). v3.1: UP rows
    get the slack KILL (kill_with_slack); the DOWN capture keeps the generator's KILL (its shell ceiling 750 s is above
    the plan budget 690 s and already leaves 30 s)."""
    e = step["l12_effect"]
    d = e["docker"]
    swap = lambda p: secrets_root + p[len(GEN_SECRETS_ROOT):] if p.startswith(GEN_SECRETS_ROOT + "/") else p
    cls = step["network_class"]
    return {"kind": "CONTAINER", "docker": {
        "name": d["name"], "labels": d["labels"], "network": "none" if cls == "NONE" else networks[cls],
        "env_files": [swap(p) for p in d["env_files"]], "env": d["env"],
        "mounts": [dict(m, source=swap(m["source"])) for m in d["mounts"]], "tmpfs": d["tmpfs"], "workdir": d["workdir"],
        "image_id": d["image_id"], "command": d["command"],
        "timeout_seconds": kill_with_slack(step) if slack else d["timeout_seconds"]},
        "receipt": {"source": "FILE", "path": e["receipt"]["path"]}}


def slack_table(spec):
    """budget floor vs effect lateness of every K9 row of a spec (CONTRACT 9.3)."""
    rows = []
    for t in spec["tasks"]:
        d = t["effect"].get("docker")
        if d:
            floor = d["timeout_seconds"] + DOCKER_MARGIN
            rows.append({"target": t["operation"], "budget": t["budget_seconds"], "kill": d["timeout_seconds"],
                         "effect_floor": floor, "max_effect_lateness": t["budget_seconds"] - floor,
                         "slack_beyond_allowance": t["budget_seconds"] - floor - rt.GATE_ALLOWANCE_SECONDS})
    for s in (spec["extended"] or {}).get("steps", []):
        d = (s["effect"] or {}).get("docker")
        if d:
            extra = 2 * rt.GATE_ALLOWANCE_SECONDS if s["step"] == "capture_launch" else 0
            floor = d["timeout_seconds"] + DOCKER_MARGIN
            rows.append({"target": s["step"], "budget": s["ceiling_seconds"], "kill": d["timeout_seconds"],
                         "effect_floor": floor, "max_effect_lateness": s["ceiling_seconds"] - floor - extra,
                         "slack_beyond_allowance": s["ceiling_seconds"] - floor - rt.GATE_ALLOWANCE_SECONDS - extra})
    return rows


def start_margin(at, horizon=6 * 3600):
    """Seconds from the instant `at` to the first second the ENGINE's start-minute rule refuses."""
    for k in range(horizon):
        if fx.start_minute_violation(at + timedelta(seconds=k)) is not None:
            return k
    return horizon


def start_windows(spec):
    """Every slot of a spec, by instant: its margin to the engine's next forbidden second and whether the whole
    [at, at + 60 s] + 45 s is allowed (margin > 105 s)."""
    rows = []
    for owner in list(spec["tasks"]) + list((spec["extended"] or {}).get("steps", [])):
        for s in owner["slots"]:
            at = rt.stamp(s["at"], rt.Hold)
            margin = start_margin(at)
            rows.append({"slot": s["slot"], "target": owner.get("operation") or owner.get("step"), "at": s["at"],
                         "brt": at.astimezone(rt.BRT).strftime("%a %d/%m %H:%M:%S"), "margin_seconds": margin,
                         "needed_seconds": START_WINDOW_SECONDS + 1, "ok": margin > START_WINDOW_SECONDS})
    return sorted(rows, key=lambda r: r["at"])


